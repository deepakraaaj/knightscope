import type { Game, PositionAnalysis } from '@/types';
import { LineStepper } from '@/components/chess/LineStepper';
import { explainPosition } from '@/chess/explanations/explain';
import { useSettings } from '@/hooks/data';
import { formatEval } from '@/utils/format';
import { forPlayer, winPercentFor } from '@/chess/positions/evaluation';
import { Badge, Modal } from '@/components/ui';
import { ClassificationBadge, ConfidenceBadge } from '@/components/chess/badges';
import { CheckCircle2, CircleAlert } from 'lucide-react';

export function WhyNotMyMove({ open, onClose, game, p }: { open: boolean; onClose: () => void; game: Game; p: PositionAnalysis | null }) {
  const settings = useSettings();
  if (!p || !p.bestMove) return null;
  const orientation = p.mover === 'w' ? 'white' : 'black';
  const exp = explainPosition(p, settings.explanationLevel);
  const yourLine = [p.actualMove, ...p.replyVariation];
  const bestLine = p.principalVariation[0] === p.bestMove ? p.principalVariation : [p.bestMove];
  const moveNo = `${Math.floor(p.ply / 2) + 1}${p.mover === 'w' ? '.' : '…'}`;
  const winYour = p.evaluationAfter ? winPercentFor(p.evaluationAfter, p.mover) : null;
  const winBest = p.evaluationBefore ? winPercentFor(p.evaluationBefore, p.mover) : null;
  return (
    <Modal open={open} onClose={onClose} title={`Why not my move? · Move ${moveNo}`} wide>
      <div className="mb-4 flex flex-wrap items-center gap-2 text-sm text-muted">
        <span>{game.white} vs {game.black}</span>
        <ClassificationBadge c={p.classification} />
        <ConfidenceBadge label={p.confidence?.label} />
        <span className="text-xs">Depth {p.depth} · evaluations shown from {p.mover === 'w' ? 'White' : 'Black'}’s side</span>
      </div>
      <div className="grid gap-6 md:grid-cols-2">
        <section aria-label="Your move" className="flex flex-col gap-3" data-testid="why-your">
          <header className="flex items-center justify-between gap-2">
            <div className="flex items-center gap-2">
              <CircleAlert className="size-4 text-orange" />
              <h3 className="font-semibold">Your move: {moveNo} {p.actualSan}</h3>
            </div>
            <Badge color="#FB923C">{formatEval(p.evaluationAfter ? forPlayer(p.evaluationAfter, p.mover) : null)}</Badge>
          </header>
          <LineStepper id="why-your" startFen={p.fen} line={yourLine} orientation={orientation} accent="#FB923C" />
          <div className="rounded-lg border border-border bg-bg p-3 text-sm">
            <div className="label mb-2">What happens</div>
            {p.replyVariation[0] && <p className="mb-2 text-muted">The line starts with your move, followed by the engine’s best reply for the opponent.</p>}
            <ul className="space-y-1.5">
              {exp.yourMove.map((t, i) => <li key={i}>{t}</li>)}
              {winYour !== null && winBest !== null && <li className="text-muted">Estimated winning chances: {winYour.toFixed(0)}% after your move vs {winBest.toFixed(0)}% with the better move.</li>}
            </ul>
          </div>
        </section>
        <section aria-label="Better move" className="flex flex-col gap-3" data-testid="why-best">
          <header className="flex items-center justify-between gap-2">
            <div className="flex items-center gap-2">
              <CheckCircle2 className="size-4 text-good" />
              <h3 className="font-semibold">Better: {moveNo} {p.bestSan}</h3>
            </div>
            <Badge color="#4ADE80">{formatEval(p.evaluationBefore ? forPlayer(p.evaluationBefore, p.mover) : null)}</Badge>
          </header>
          <LineStepper id="why-best" startFen={p.fen} line={bestLine} orientation={orientation} accent="#4ADE80" />
          <div className="rounded-lg border border-border bg-bg p-3 text-sm">
            <div className="label mb-2">Why it is better</div>
            <ul className="space-y-1.5">{exp.betterMove.map((t, i) => <li key={i}>{t}</li>)}</ul>
          </div>
        </section>
      </div>
      <p className="mt-4 text-xs text-muted">Explanations are generated by rules checked against the engine lines shown. They are not AI-written. Evaluations are Stockfish estimates at the tested depth.</p>
    </Modal>
  );
}
